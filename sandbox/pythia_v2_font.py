ADVANCE = 5.6          # cell units per character, spacing included
CAP = 6.0              # cap height in cell units


def advance(size):
    return ADVANCE * size * 0.72 / CAP


def strokes(text, x, y, size, anchor="center"):
    unit = size * 0.72 / CAP
    width = (len(text) * ADVANCE - (ADVANCE - 4)) * unit
    if anchor == "w":
        left = x
    elif anchor == "e":
        left = x - width
    else:
        left = x - width / 2
    top = y - CAP * unit / 2
    out = []
    for k, ch in enumerate(text):
        glyph = GLYPHS.get(ch)
        if glyph is None:
            glyph = GLYPHS.get(ch.upper(), [])
        ox = left + k * ADVANCE * unit
        for line in glyph:
            out.append([(ox + gx * unit, top + gy * unit) for gx, gy in line])
    return out
