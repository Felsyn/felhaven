"""
test_environment_lock.py — the venv running this suite is exactly the lockfile.

`requirements.txt` is a lock: every package pinned to one version and hashed,
compiled from `requirements.in` by pip-compile on one Python minor version
(CONVENTIONS §11). It protects nothing unless the environment matches it.
The ways the two quietly drift apart are the ones checked here:

  - a hand `pip install` into `.venv`. The leftover is code on the import
    path that nothing declared, and nothing will ever upgrade;
  - a lock edited or recompiled without rebuilding the venv, so the pins say
    one thing and the disk another;
  - a venv built on a different Python than the lock was compiled for. pip
    resolves by interpreter, so one `.in` can lock different packages on two
    minor versions (on 3.14 it quietly picks a kokoro-onnx from 2025);
  - a pin added by hand without hashes, or a package declared in an `.in`
    file and never compiled into its lock.

Two installed states are valid: the runtime lock alone (CI's test job, which
proves the app and this suite need nothing more), or the runtime lock plus the
dev lock (mypy and its stubs, to run the type check locally). `pip` itself is
the one package allowed beyond them: the venv ships it and nothing imports it.

CI builds its venv from the same lock and runs this, so a green run means CI
tested the environment Felhaven runs in.

    python -X utf8 -m unittest tests.test_environment_lock
"""

import importlib.metadata
import os
import re
import sys
import sysconfig
import unittest

_APP_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_RUNTIME_IN = os.path.join(_APP_ROOT, "requirements.in")
_RUNTIME_LOCK = os.path.join(_APP_ROOT, "requirements.txt")
_DEV_IN = os.path.join(_APP_ROOT, "requirements-dev.in")
_DEV_LOCK = os.path.join(_APP_ROOT, "requirements-dev.txt")

# pip-compile's header names the interpreter the lock was resolved on.
_HEADER_PYTHON = re.compile(r"^# This file is autogenerated by pip-compile with Python (\d+)\.(\d+)\s*$")
_PIN = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s;\\]+)")
_HASH = "--hash=sha256:"
_ALLOWED_EXTRA = {"pip"}


def _norm(name):
    """PEP 503 name: 'Typing_Extensions' and 'typing-extensions' are one package."""
    return re.sub(r"[-_.]+", "-", name).lower()


def _read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read().splitlines()


def _lock(path):
    """({name: version}, [lines that aren't an exact pin], [pins with no hash]).

    A requirement starts at column 0; its hashes and pip-compile's '# via'
    notes are the indented continuation lines under it."""
    pins, bad, hashed, name = {}, [], {}, None
    for line in _read(path):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0].isspace():
            if name is not None and _HASH in line:
                hashed[name] = True
            continue
        m = _PIN.match(line)
        if m is None:
            bad.append(line)
            name = None
            continue
        name = _norm(m.group(1))
        pins[name] = m.group(2)
        hashed[name] = _HASH in line
    return pins, bad, sorted(n for n, ok in hashed.items() if not ok)


def _lock_python(path):
    """(major, minor) from the lock's header, or None if it has none."""
    for line in _read(path):
        m = _HEADER_PYTHON.match(line)
        if m:
            return int(m.group(1)), int(m.group(2))
    return None


def _declared(path):
    """Package names an .in file asks for (options like '-c' skipped)."""
    names = []
    for line in _read(path):
        text = line.split("#", 1)[0].strip()
        if text and not text.startswith("-"):
            names.append(_norm(re.split(r"[\s<>=!~;\[]", text, maxsplit=1)[0]))
    return names


def _installed():
    """{name: version} for what this interpreter's own site-packages holds."""
    paths = sorted({sysconfig.get_paths()["purelib"], sysconfig.get_paths()["platlib"]})
    found = {}
    for dist in importlib.metadata.distributions(path=paths):
        name = dist.metadata["Name"]
        if name:
            found[_norm(name)] = dist.version
    return found


class TestLockFiles(unittest.TestCase):
    """The lock files themselves: shape, hashes, and agreement with their inputs."""

    def test_every_line_is_an_exact_hashed_pin(self):
        for path in (_RUNTIME_LOCK, _DEV_LOCK):
            with self.subTest(lock=os.path.basename(path)):
                pins, bad, unhashed = _lock(path)
                self.assertTrue(pins, "an empty lock guards nothing")
                self.assertEqual(bad, [], "lines that are not an exact 'name==version' pin")
                self.assertEqual(unhashed, [], "pins with no --hash: recompile, don't hand-edit")

    def test_both_locks_name_the_same_python(self):
        runtime = _lock_python(_RUNTIME_LOCK)
        self.assertIsNotNone(runtime, "requirements.txt has no pip-compile header naming its Python")
        self.assertEqual(_lock_python(_DEV_LOCK), runtime)

    def test_every_declared_package_is_in_its_lock(self):
        for source, lock in ((_RUNTIME_IN, _RUNTIME_LOCK), (_DEV_IN, _DEV_LOCK)):
            pins = _lock(lock)[0]
            for name in _declared(source):
                with self.subTest(declared=name):
                    self.assertTrue(
                        name in pins,
                        f"{name} is in {os.path.basename(source)} but not in "
                        f"{os.path.basename(lock)}: recompile the lock")

    def test_packages_in_both_locks_have_one_version(self):
        runtime, dev = _lock(_RUNTIME_LOCK)[0], _lock(_DEV_LOCK)[0]
        clash = {n: (runtime[n], dev[n]) for n in runtime.keys() & dev.keys() if runtime[n] != dev[n]}
        self.assertEqual(clash, {}, "requirements-dev.in's '-c requirements.txt' should "
                                    "prevent this: recompile the dev lock")


class TestInstalledEnvironment(unittest.TestCase):
    """What this interpreter actually has installed, against the locks."""

    def test_the_suite_runs_in_a_venv(self):
        self.assertNotEqual(sys.prefix, sys.base_prefix,
                            "run the suite with the venv's python (SETUP.md §9), not a system one")

    def test_python_is_the_one_the_lock_was_compiled_for(self):
        want = _lock_python(_RUNTIME_LOCK)
        have = tuple(sys.version_info[:2])
        self.assertEqual(have, want, f"this is Python {have[0]}.{have[1]}; the lock was compiled "
                                     f"on {want}. Rebuild the venv on that Python (SETUP.md §2)")

    def test_installed_packages_are_exactly_the_lock(self):
        runtime, dev = _lock(_RUNTIME_LOCK)[0], _lock(_DEV_LOCK)[0]
        installed = _installed()
        # One dev-only package present means the whole dev lock should be.
        with_dev = bool(installed.keys() & (dev.keys() - runtime.keys()))
        want = {**runtime, **dev} if with_dev else runtime
        extra = sorted(installed.keys() - want.keys() - _ALLOWED_EXTRA)
        missing = sorted(want.keys() - installed.keys())
        wrong = sorted(f"{n} {installed[n]} (lock: {want[n]})"
                       for n in installed.keys() & want.keys() if installed[n] != want[n])
        if extra or missing or wrong:
            self.fail(
                f"this venv is not the {'runtime + dev' if with_dev else 'runtime'} lock.\n"
                f"  installed, not locked: {', '.join(extra) or '-'}\n"
                f"  locked, not installed: {', '.join(missing) or '-'}\n"
                f"  wrong version:         {', '.join(wrong) or '-'}\n"
                f"Rebuild the venv from the lock (SETUP.md §2); never pip install into it by hand.")


if __name__ == "__main__":
    unittest.main(verbosity=2)
